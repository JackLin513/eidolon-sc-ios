    private func assertGolden(_ json: String, adultMode: Bool) throws {
        let expected = try XCTUnwrap(
            try JSONSerialization.jsonObject(with: Data(json.utf8)) as? [String: Any]
        )
        let actual = JudgeQuestions.payload(adultMode: adultMode)
        for key in ["affinity", "out_of_line", "manipulation"] {
            let want = try XCTUnwrap(expected[key] as? [String: Any], key)
            let got = try XCTUnwrap(actual[key] as? [String: Any], key)
            XCTAssertEqual(
                NSDictionary(dictionary: got), NSDictionary(dictionary: want), key
            )
        }
    }

